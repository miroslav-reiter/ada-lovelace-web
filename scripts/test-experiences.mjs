import assert from 'node:assert/strict';
import {initialMachine,stepMachine,runMachine,diplomaRank} from '../dist/machine-core.mjs';
const math=['set','add','multiply','show'];
assert.equal(runMachine('math',math).memory,10);
assert.equal(runMachine('math',math).status,'success');
assert.equal(runMachine('math',['set','multiply','add','show']).message,'errorGoal');
assert.equal(runMachine('math',['set','show','add']).message,'errorLast');
assert.equal(runMachine('math',['set','add']).message,'errorOutput');
assert.equal(runMachine('math',[]).message,'needCards');
assert.equal(runMachine('math',['water']).message,'errorUnknown');
assert.equal(runMachine('math',Array(13).fill('add')).message,'full');
let state=initialMachine();
const original={...state};
state=stepMachine(state,'math',math);
assert.deepEqual(original,initialMachine());
assert.equal(state.index,1);
assert.equal(state.memory,2);
state=stepMachine(state,'math',math);
assert.equal(state.memory,5);
state=stepMachine(state,'math',math);
state=stepMachine(state,'math',math);
assert.equal(state.status,'success');
assert.deepEqual(stepMachine(state,'math',math),state);
const tea=['water','heat','leaves','steep','pour'];
assert.equal(runMachine('tea',tea).status,'success');
assert.equal(runMachine('tea',tea).stage,5);
assert.equal(runMachine('tea',['heat','pour']).message,'errorEmpty');
assert.equal(runMachine('tea',['water','leaves','pour']).message,'errorCold');
assert.equal(runMachine('tea',['water','heat','steep','pour']).message,'errorLeaves');
assert.equal(runMachine('tea',['water','heat','leaves','pour']).message,'errorSteep');
assert.equal(runMachine('tea',['water','water','pour']).message,'errorRepeat');
assert.equal(diplomaRank(0,12),'rankLow');
assert.equal(diplomaRank(6,12),'rankMid');
assert.equal(diplomaRank(10,12),'rankHigh');
assert.equal(diplomaRank(12,12),'rankHigh');
assert.throws(()=>diplomaRank(13,12),RangeError);
console.log('PASS: arithmetic, tea prerequisites, order errors, missing output, bounds, stepping, immutable state and diploma ranks.');
